export function translateApiError(message, locale) {
  if (!message || locale === 'en') return message;
  const staticMatch = STATIC[message];
  if (staticMatch) return staticMatch[locale] || message;
  for (const entry of DYNAMIC) {
    const m = message.match(entry.pattern);
    if (m && entry[locale]) return entry[locale](m);
  }
  return message;
}
